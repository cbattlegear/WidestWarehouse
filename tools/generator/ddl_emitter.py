from __future__ import annotations

from pathlib import Path

from .graph import topological_sort
from .model_loader import Column, Model, Table

HEADER = "-- Generated by tools.generator. Do not hand-edit.\n\n"
SCHEMAS = ["ref", "dim", "bridge", "fact", "stg", "etl"]
FOLDERS = [
    "00_database",
    "10_reference",
    "20_dimensions",
    "30_bridges",
    "40_facts",
    "50_constraints",
    "60_indexes",
    "70_views",
    "80_etl_control",
    "90_staging",
]


def q(name: str) -> str:
    return f"[{name}]"


def full_name(table: Table) -> str:
    return f"{q(table.schema)}.{q(table.name)}"


def sql_type(type_name: str) -> str:
    t = type_name.lower()
    for base in ("nvarchar", "datetime2", "decimal", "time", "char", "varbinary", "binary"):
        if t.startswith(base + "("):
            return base.upper() + t[len(base):]
    return t.upper()


def column_sql(col: Column) -> str:
    parts = [q(col.name), sql_type(col.type)]
    if col.identity:
        parts.append("IDENTITY(1,1)")
    parts.append("NULL" if col.nullable else "NOT NULL")
    if col.default is not None:
        parts.append(f"DEFAULT {col.default}")
    return " ".join(parts)


def audit_columns(table: Table | None = None) -> list[Column]:
    cols = [
        Column("BatchId", "bigint", nullable=False, default="0"),
        Column("LoadedAtUtc", "datetime2(3)", nullable=False, default="SYSUTCDATETIME()"),
    ]
    if table is None or table.name != "SourceSystem":
        cols.insert(0, Column("SourceSystemKey", "int", nullable=False, default="-1"))
    return cols


def scd2_columns() -> list[Column]:
    return [
        Column("EffectiveFromUtc", "datetime2(3)", nullable=False),
        Column("EffectiveToUtc", "datetime2(3)", nullable=False, default="'9999-12-31'"),
        Column("IsCurrent", "bit", nullable=False, default="1"),
        Column("RowHash", "binary(32)", nullable=False),
    ]


def table_columns(table: Table) -> list[Column]:
    cols: list[Column] = []
    if table.kind in {"ref", "dim", "bridge"}:
        if table.explicit_key and table.business_key:
            cols.append(table.business_key)
        else:
            cols.append(Column(table.key_column, "int", nullable=False, identity=True))
            if table.business_key:
                cols.append(table.business_key)
        cols.extend(Column(fk.column_name, "int", nullable=fk.nullable, default=None if fk.nullable else "-1") for fk in table.foreign_keys)
        cols.extend(table.columns)
        cols.extend(audit_columns(table))
        if table.scd == "type2":
            cols.extend(scd2_columns())
    elif table.kind == "fact":
        cols.append(Column(table.key_column, "bigint", nullable=False, identity=True))
        cols.extend(Column(fk.column_name, "int", nullable=fk.nullable, default="-1") for fk in table.foreign_keys)
        cols.extend(table.columns)
        if table.fact_type == "accumulating_snapshot":
            cols.append(Column(f"{table.name}LagDays", "int", nullable=True))
        cols.extend(audit_columns(table))
    elif table.kind == "etl":
        cols.extend(table.columns)
    return cols


def create_table_sql(table: Table) -> str:
    cols = [f"    {column_sql(c)}" for c in table_columns(table)]
    pk_cols = table.primary_key or [table.key_column]
    clustered = "NONCLUSTERED" if table.kind == "fact" and table.columnstore else "CLUSTERED"
    if table.kind == "etl":
        pk_type = "CLUSTERED"
        pk_cols = table.primary_key
    else:
        pk_type = clustered
    if pk_cols:
        cols.append(f"    CONSTRAINT {q('PK_' + table.schema + '_' + table.name)} PRIMARY KEY {pk_type} ({', '.join(q(c) for c in pk_cols)})")
    return (
        f"IF OBJECT_ID(N'{table.schema}.{table.name}', N'U') IS NULL\n"
        "BEGIN\n"
        f"CREATE TABLE {full_name(table)} (\n"
        + ",\n".join(cols)
        + "\n);\nEND\nGO\n"
    )


def database_sql() -> str:
    schema_sql = "\n".join(
        f"IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = N'{s}') EXEC(N'CREATE SCHEMA {q(s)}');\nGO"
        for s in SCHEMAS
    )
    return (
        HEADER
        + "-- DatabaseName is a sqlcmd variable. build_all.sql supplies a default,\n"
        + "-- so pass -v DatabaseName=\"MyDw\" only to target a different database.\n"
        + "IF DB_ID(N'$(DatabaseName)') IS NULL\n"
        + "BEGIN\n"
        + "    DECLARE @sql nvarchar(max) = N'CREATE DATABASE '\n"
        + "        + QUOTENAME(N'$(DatabaseName)')\n"
        + "        + N' COLLATE SQL_Latin1_General_CP1_CI_AS;';\n"
        + "    EXEC sys.sp_executesql @sql;\n"
        + "END\nGO\nUSE [$(DatabaseName)];\nGO\n"
        + schema_sql
        + "\n"
    )


def ensure_output_dirs(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for folder in FOLDERS:
        path = out / folder
        path.mkdir(parents=True, exist_ok=True)
        for sql in path.glob("*.sql"):
            sql.unlink()
    build = out / "build_all.sql"
    if build.exists():
        build.unlink()


def write_grouped(out: Path, folder: str, tables: list[Table], prefix_start: int = 10) -> list[Path]:
    written: list[Path] = []
    groups: dict[str, list[Table]] = {}
    for table in tables:
        groups.setdefault(table.subject_area, []).append(table)
    for idx, subject in enumerate(sorted(groups), prefix_start):
        path = out / folder / f"{idx:02d}_{subject}.sql"
        body = HEADER + f"-- Subject area: {subject}\n\n" + "\n".join(create_table_sql(t) for t in sorted(groups[subject], key=lambda t: (t.schema, t.name)))
        path.write_text(body, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def emit_tables(model: Model, out: Path) -> list[Path]:
    paths: list[Path] = []
    db = out / "00_database" / "00_database.sql"
    db.write_text(database_sql(), encoding="utf-8", newline="\n")
    paths.append(db)

    ordered = topological_sort(model)
    paths += write_grouped(out, "10_reference", [t for t in ordered if t.kind == "ref"])
    dims = [t for t in ordered if t.kind == "dim"]
    dims.sort(key=lambda t: (0 if t.is_hierarchy else 1, t.hierarchy_name or "", t.hierarchy_ordinal or 0, t.subject_area, t.name))
    paths += write_grouped(out, "20_dimensions", dims)
    paths += write_grouped(out, "30_bridges", [t for t in ordered if t.kind == "bridge"])
    paths += write_grouped(out, "40_facts", [t for t in ordered if t.kind == "fact"])
    paths += write_grouped(out, "80_etl_control", [t for t in ordered if t.kind == "etl"])
    return paths
